import { describe, expect, test } from "bun:test";
import { digestJson, stableYaml, type Json } from "@archcontext/contracts";
import {
  architectureLayerGroups,
  exportDocumentationLikeC4Model,
  exportDocumentationStructurizrWorkspace,
  exportMermaidModel,
  loadNativeModelFromModelFiles,
  type NativeModel
} from "../src/index";

const relations: NativeModel["relations"] = [
  { id: "relation.billing-store", kind: "writes", source: "module.billing", target: "datastore.billing", intent: "Persists invoices." },
  { id: "relation.api-billing", kind: "calls", source: "module.api", target: "module.billing", intent: "Bills requests." },
  { id: "relation.billing-ledger", kind: "depends-on", source: "module.billing", target: "module.ledger", intent: "Posts entries." }
];

const layered: NativeModel = {
  nodes: [
    { id: "module.ledger", kind: "module", name: "Ledger", layer: "domain" },
    { id: "module.api", kind: "module", name: "API", layer: "interface-adapters" },
    { id: "datastore.billing", kind: "datastore", name: "Billing DB" },
    { id: "module.billing", kind: "module", name: "Billing", layer: "domain" }
  ],
  relations
};

const ungrouped: NativeModel = {
  nodes: layered.nodes.map(({ layer: _layer, ...node }) => node),
  relations
};

const reversed = (model: NativeModel): NativeModel => ({ nodes: [...model.nodes].reverse(), relations: [...model.relations].reverse() });

const LIKEC4_PREFIX = [
  "// Generated by ArchContext. Native model remains source of truth.",
  "specification {",
  "  element capability",
  "  element module",
  "  element component",
  "  element interface",
  "  element datastore",
  "  element external_system",
  "}",
  "",
  "model {",
  "  datastore_billing = datastore \"Billing DB\"",
  "  module_api = module \"API\"",
  "  module_billing = module \"Billing\"",
  "  module_ledger = module \"Ledger\"",
  "  module_api -> module_billing \"calls\"",
  "  module_billing -> module_ledger \"depends-on\"",
  "  module_billing -> datastore_billing \"writes\"",
  "}",
  ""
];

function structurizrContent(elements: Record<string, Json>[]): string {
  return `${JSON.stringify({
    schemaVersion: "archcontext.structurizr-export/v1",
    name: "ArchContext Architecture",
    model: {
      elements,
      relationships: [
        { id: "relation.api-billing", sourceId: "module.api", destinationId: "module.billing", description: "calls" },
        { id: "relation.billing-ledger", sourceId: "module.billing", destinationId: "module.ledger", description: "depends-on" },
        { id: "relation.billing-store", sourceId: "module.billing", destinationId: "datastore.billing", description: "writes" }
      ]
    },
    views: {
      systemLandscape: {
        key: "archcontext-landscape",
        include: ["datastore.billing", "module.api", "module.billing", "module.ledger"]
      }
    }
  }, null, 2)}\n`;
}

describe("architecture layer groups (ADR-0049)", () => {
  test("groups nodes only by the explicit layer field, layers by name and members by id", () => {
    const grouping = architectureLayerGroups(layered);
    expect(grouping.layers.map((group) => ({ layer: group.layer, nodeIds: group.nodes.map((node) => node.id) }))).toEqual([
      { layer: "domain", nodeIds: ["module.billing", "module.ledger"] },
      { layer: "interface-adapters", nodeIds: ["module.api"] }
    ]);
    expect(grouping.ungroupedNodes.map((node) => node.id)).toEqual(["datastore.billing"]);
    expect([...grouping.layerByNodeId.entries()]).toEqual([
      ["module.api", "interface-adapters"],
      ["module.billing", "domain"],
      ["module.ledger", "domain"]
    ]);
    // `parent` and id prefixes never imply a layer.
    const parented = architectureLayerGroups({ nodes: [{ id: "module.child", kind: "module", name: "Child", parent: "capability.domain" }] });
    expect(parented.layers).toEqual([]);
    expect(parented.ungroupedNodes.map((node) => node.id)).toEqual(["module.child"]);
  });

  test("an invalid layer value fails closed", () => {
    for (const layer of ["Domain", "domain services", "domain_core", ""]) {
      expect(() => architectureLayerGroups({ nodes: [{ id: "module.a", kind: "module", name: "A", layer }] })).toThrow(/architecture-node-layer-invalid: module\.a/);
    }
    expect(() => architectureLayerGroups({ nodes: [{ id: "module.a", kind: "module", name: "A", layer: 3 as unknown as string }] })).toThrow(/architecture-node-layer-invalid/);
  });

  test("Mermaid renders one subgraph per layer and leaves ungrouped nodes and edges as they were", () => {
    const expected = [
      "%% Generated by ArchContext. Native model remains source of truth.",
      "flowchart LR",
      "  subgraph layer__domain[\"domain\"]",
      "    module_billing[\"Billing\"]",
      "    module_ledger[\"Ledger\"]",
      "  end",
      "  subgraph layer__interface_adapters[\"interface-adapters\"]",
      "    module_api[\"API\"]",
      "  end",
      "  datastore_billing[\"Billing DB\"]",
      "  module_api -->|\"calls\"| module_billing",
      "  module_billing -->|\"depends-on\"| module_ledger",
      "  module_billing -->|\"writes\"| datastore_billing",
      ""
    ].join("\n");
    const first = exportMermaidModel(layered);
    expect(first.files[0]!.content).toBe(expected);
    expect(first.digest).toBe(digestJson({ format: "mermaid", content: expected } as unknown as Json));
    const second = exportMermaidModel(reversed(layered));
    expect(second.files[0]!.content).toBe(first.files[0]!.content);
    expect(second.digest).toBe(first.digest);
  });

  test("LikeC4 renders each layer as a view group ahead of include *", () => {
    const expected = [
      ...LIKEC4_PREFIX,
      "views {",
      "  view index {",
      "    group \"domain\" {",
      "      include module_billing",
      "      include module_ledger",
      "    }",
      "    group \"interface-adapters\" {",
      "      include module_api",
      "    }",
      "    include *",
      "    autoLayout TopBottom",
      "  }",
      "}",
      ""
    ].join("\n");
    const first = exportDocumentationLikeC4Model(layered);
    expect(first.files[0]!.content).toBe(expected);
    expect(exportDocumentationLikeC4Model(reversed(layered))).toEqual(first);
  });

  test("Structurizr sets each element's group to its layer", () => {
    const expected = structurizrContent([
      { id: "datastore.billing", name: "Billing DB", type: "Database", tags: ["datastore"] },
      { id: "module.api", name: "API", type: "Container", tags: ["module"], group: "interface-adapters" },
      { id: "module.billing", name: "Billing", type: "Container", tags: ["module"], group: "domain" },
      { id: "module.ledger", name: "Ledger", type: "Container", tags: ["module"], group: "domain" }
    ]);
    const first = exportDocumentationStructurizrWorkspace(layered);
    expect(first.files[0]!.content).toBe(expected);
    expect(first.digest).toBe(digestJson(JSON.parse(expected) as Json));
    expect(exportDocumentationStructurizrWorkspace(reversed(layered))).toEqual(first);
  });

  test("a model with no layer renders the pre-layer bytes and digests in every exporter", () => {
    const mermaid = [
      "%% Generated by ArchContext. Native model remains source of truth.",
      "flowchart LR",
      "  datastore_billing[\"Billing DB\"]",
      "  module_api[\"API\"]",
      "  module_billing[\"Billing\"]",
      "  module_ledger[\"Ledger\"]",
      "  module_api -->|\"calls\"| module_billing",
      "  module_billing -->|\"depends-on\"| module_ledger",
      "  module_billing -->|\"writes\"| datastore_billing",
      ""
    ].join("\n");
    const likec4 = [...LIKEC4_PREFIX, "views {", "  view index {", "    include *", "    autoLayout TopBottom", "  }", "}", ""].join("\n");
    const structurizr = structurizrContent([
      { id: "datastore.billing", name: "Billing DB", type: "Database", tags: ["datastore"] },
      { id: "module.api", name: "API", type: "Container", tags: ["module"] },
      { id: "module.billing", name: "Billing", type: "Container", tags: ["module"] },
      { id: "module.ledger", name: "Ledger", type: "Container", tags: ["module"] }
    ]);
    for (const model of [ungrouped, reversed(ungrouped)]) {
      expect(exportMermaidModel(model)).toEqual({
        format: "mermaid",
        digest: digestJson({ format: "mermaid", content: mermaid } as unknown as Json),
        files: [{ path: ".archcontext/generated/architecture.mmd", content: mermaid }]
      });
      expect(exportDocumentationLikeC4Model(model)).toEqual({
        format: "likec4",
        digest: digestJson({ format: "likec4", content: likec4 } as unknown as Json),
        files: [{ path: "docs/architecture/diagrams/architecture.likec4", content: likec4 }]
      });
      expect(exportDocumentationStructurizrWorkspace(model)).toEqual({
        format: "structurizr",
        digest: digestJson(JSON.parse(structurizr) as Json),
        files: [{ path: "docs/architecture/diagrams/architecture.structurizr.json", content: structurizr }]
      });
    }
  });

  test("the YAML model loader carries layer through and rejects an invalid one", () => {
    const node = { schemaVersion: "archcontext.node/v2", id: "module.api", kind: "module", name: "API", status: "active", summary: "Serves requests.", layer: "interface-adapters" };
    const loaded = loadNativeModelFromModelFiles(new Map([[".archcontext/model/nodes/module.api.yaml", stableYaml(node as Json)]]));
    expect(loaded.nodes[0]!.layer).toBe("interface-adapters");
    expect(() => loadNativeModelFromModelFiles(new Map([[".archcontext/model/nodes/module.api.yaml", stableYaml({ ...node, layer: "Interface Adapters" } as Json)]])))
      .toThrow(/architecture-node-layer-invalid: module\.api/);
  });
});

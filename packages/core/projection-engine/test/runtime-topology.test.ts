const shuffled = (model: NativeModel): NativeModel => ({
  nodes: [...model.nodes].reverse(),
  relations: [...model.relations.slice(3), ...model.relations.slice(0, 3)].reverse()
});
const withoutTopology: NativeModel = {
  nodes: [
    { id: "capability.shop", kind: "capability", name: "Shop" },
    { id: "component.shop.api", kind: "component", name: "API", parent: "capability.shop" }
  ],
  relations: [{ id: "relation.shop.api-capability", kind: "implements", source: "component.shop.api", target: "capability.shop", intent: "Implements the shop." }]
};

const sourceDigest = `sha256:${"3".repeat(64)}`;
const provenance = architectureDocumentationProjectionProvenance({
  sourceTreeDigest: sourceDigest,
  modelDigest: sourceDigest,
  rendererVersion: ARCHITECTURE_DOCS_RENDERER_VERSION,
  layoutVersion: ARCHITECTURE_DOCS_LAYOUT_VERSION,
  generatedFrom: { codeGraphPackage: "@colbymchenry/codegraph", codeGraphVersion: "1.6.2" }
});
const render = (model: NativeModel) => renderArchitectureDocumentationProjection({
  model,
  provenance,
  sourceDigest,
  sourceFootprints: [],
  sourceScaleSignals: [],
  importGraphs: [],
  selectorEvidence: []
});


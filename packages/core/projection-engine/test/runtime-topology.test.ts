describe("runtime topology view (ADR-0049)", () => {
  test("Mermaid nests namespaces, orders mount stacks and links deployed components", () => {
    const exported = exportRuntimeTopologyMermaid(topology());
    expect(exported.files).toEqual([{ path: "docs/architecture/diagrams/runtime-topology.mmd", content: EXPECTED_MERMAID }]);
    expect(exported.digest).toBe(digestJson({ format: "mermaid", content: EXPECTED_MERMAID } as unknown as Json));
  });

  test("the summary page lists namespaces, processes and mount stacks in order", () => {
    expect(renderRuntimeTopologySummary(topology(), "docs/architecture/runtime-topology.md")).toBe(EXPECTED_SUMMARY);
  });

  test("shuffled input renders the same bytes", () => {
    expect(exportRuntimeTopologyMermaid(shuffled(topology()))).toEqual(exportRuntimeTopologyMermaid(topology()));
    expect(renderRuntimeTopologySummary(shuffled(topology()), "docs/architecture/runtime-topology.md")).toBe(EXPECTED_SUMMARY);
    const first = render(topology());
    const second = render(shuffled(topology()));
    expect(second.projectionDigest).toBe(first.projectionDigest);
    expect(second.files.map(({ path, body }) => ({ path, body }))).toEqual(first.files.map(({ path, body }) => ({ path, body })));
    expect(second.manifest.body).toBe(first.manifest.body);
  });

  test("a topology model without source.include adds both whole-model targets with no source stamps", () => {
    const plan = render(topology());
    const diagram = plan.files.find((file) => file.target.type === "diagram-runtime-topology")!;
    const summary = plan.files.find((file) => file.target.type === "runtime-topology-summary")!;
    expect(diagram.path).toBe("docs/architecture/diagrams/runtime-topology.mmd");
    expect(diagram.body).toBe(EXPECTED_MERMAID);
    expect(summary.path).toBe("docs/architecture/runtime-topology.md");
    expect(summary.body).toBe(EXPECTED_SUMMARY);
    for (const file of [diagram, summary]) {
      expect(file.target.ownership).toBe("generated");
      expect(file.target.scope).toEqual({ kind: "diagram", id: "runtime-topology" });
      expect(file.sourceStamps).toBeUndefined();
      // With no source.include the topology is model-authored with no source anchor: the rows carry
      // no stamp, so freshness never reports these targets as verified by anything.
      const row = plan.renderedTargets[file.target.targetId]!;
      expect(row.sourceStamps).toBeUndefined();
      expect(row.scale).toBeUndefined();
    }
    // Topology nodes get no entity summary; the topology summary covers them.
    const entityIds = plan.targets.filter((target) => target.type === "entity-summary").map((target) => target.scope.id);
    expect(entityIds).toEqual(["capability.shop", "component.shop.api"]);
    const index = plan.files.find((file) => file.path === "docs/architecture/index.md")!.body;
    expect(index).toContain([
      "- [LikeC4](diagrams/architecture.likec4)",
      "- [Runtime topology Mermaid](diagrams/runtime-topology.mmd)",
      "- [Runtime topology](runtime-topology.md)",
      "- [Decision index](decisions/index.md)"
    ].join("\n"));
  });

  test("a model without topology nodes keeps its target set and index", () => {
    const plan = render(withoutTopology);
    expect(plan.targets.map((target) => target.type).sort()).toEqual([
      "architecture-changelog",
      "architecture-index",
      "decision-index",
      "diagram-likec4",
      "diagram-mermaid",
      "diagram-structurizr",
      "entity-summary",
      "entity-summary",
      "relation-summary"
    ]);
    const index = plan.files.find((file) => file.path === "docs/architecture/index.md")!.body;
    expect(index).toContain(DEFAULT_PROJECTIONS);
    expect(index).not.toContain("runtime-topology");
    const isTopologyTarget = (type: string) => type === "diagram-runtime-topology" || type === "runtime-topology-summary";
    expect(plan.targets.some((target) => isTopologyTarget(target.type))).toBe(false);
    // The repo-harness profile adds the targets under the same condition.
    const capability = { id: "capability.shop.storefront", kind: "capability", name: "Storefront", extensions: { contractFiles: { agents: "shop/AGENTS.md", claude: "shop/CLAUDE.md" } } };
    const repoHarness = (nodes: NativeModel["nodes"]) => resolveArchitectureDocumentationLayout({ nodes, relations: [], profile: REPO_HARNESS_PROJECTION_PROFILE });
    expect(repoHarness([capability]).targets.some((target) => isTopologyTarget(target.type))).toBe(false);
    expect(repoHarness([capability, { id: "process.shop.web", kind: "process", name: "Web" }]).targets.filter((target) => isTopologyTarget(target.type)).map((target) => target.path))
      .toEqual(["docs/architecture/diagrams/runtime-topology.mmd", "docs/architecture/runtime-topology.md"]);
  });

  test("an invalid topology fails closed instead of rendering a guessed placement", () => {
    const model = topology();
    const runsInComponent = { ...model, relations: [...model.relations, { id: "relation.bad", kind: "runs-in", source: "process.shop.cron", target: "component.shop.api", intent: "bad" }] };
    expect(() => exportRuntimeTopologyMermaid(runsInComponent)).toThrow(/runtime-topology-model-invalid: relation\.bad target topology-relation-target-kind-invalid/);
    expect(() => render(runsInComponent)).toThrow(/runtime-topology-model-invalid/);
    const brokenMount = { ...model, nodes: model.nodes.map((node) => node.id === "mount.shop.tmp" ? { ...node, mount: { target: "tmp", mode: "rw", order: 0 } } : node) };
    expect(() => exportRuntimeTopologyMermaid(brokenMount)).toThrow("runtime-topology-mount-invalid: mount.shop.tmp");
    const untypedNamespace = { ...model, nodes: model.nodes.map((node) => node.id === "namespace.shop.host" ? { ...node, namespace: { type: "cgroup" } } : node) };
    expect(() => exportRuntimeTopologyMermaid(untypedNamespace)).toThrow("runtime-topology-namespace-invalid: namespace.shop.host");
  });

  test("LikeC4 and Structurizr map topology kinds explicitly", () => {
    const likec4 = exportDocumentationLikeC4Model(topology()).files[0]!.content;
    expect(likec4).toContain("  element external_system\n  element process\n  element namespace\n  element mount\n}");
    expect(likec4).toContain("  process_shop_api_server = process \"API server\"");
    expect(likec4).toContain("  namespace_shop_pod = namespace \"Shop pod\"");
    expect(likec4).toContain("  mount_shop_tmp = mount \"Scratch\"");
    const elements = JSON.parse(exportDocumentationStructurizrWorkspace(topology()).files[0]!.content).model.elements as { id: string; type: string }[];
    const typeOf = (id: string) => elements.find((element) => element.id === id)!.type;
    expect([typeOf("namespace.shop.pod"), typeOf("process.shop.worker"), typeOf("mount.shop.tmp")]).toEqual(["Deployment Node", "Container Instance", "Infrastructure Node"]);
    expect(exportDocumentationLikeC4Model(withoutTopology).files[0]!.content).toContain("  element external_system\n}");
  });

  test("a topology node's source.include is stamped on both topology rows, never on an ancestor", () => {
    const model = topology();
    const anchored = (nodes: Record<string, { parent?: string; include: string[] }>): NativeModel => ({
      ...model,
      nodes: model.nodes.map((node) => {
        const declared = nodes[node.id];
        return declared === undefined ? node : { ...node, ...(declared.parent === undefined ? {} : { parent: declared.parent }), source: { include: declared.include } };
      })
    });
    // A namespace's parent chain holds only namespaces and a process may have no parent at all:
    // both used to fail with projection-footprint-uncovered. A process under a capability is not
    // attributed to the capability either.
    const declared = anchored({
      "namespace.shop.pod": { include: ["k8s/*.yaml"] },
      "process.shop.cron": { include: ["compose.yaml"] },
      "process.shop.worker": { parent: "capability.shop", include: ["compose.yaml"] }
    });
    expect([...architectureProjectionFootprintOwners(declared).entries()]).toEqual([
      ["namespace.shop.pod", "runtime-topology"],
      ["process.shop.cron", "runtime-topology"],
      ["process.shop.worker", "runtime-topology"]
    ]);
    expect(architectureProjectionStampedNodeIds(declared)).toEqual(["namespace.shop.pod", "process.shop.cron", "process.shop.worker"]);

    const footprint = (digit: string) => `sha256:${digit.repeat(64)}`;
    const renderStamped = (cronDigest: string) => renderArchitectureDocumentationProjection({
      model: declared,
      provenance,
      sourceDigest,
      sourceFootprints: [
        { nodeId: "namespace.shop.pod", fileCount: 2, digest: footprint("a") },
        { nodeId: "process.shop.cron", fileCount: 1, digest: cronDigest },
        { nodeId: "process.shop.worker", fileCount: 1, digest: cronDigest }
      ],
      sourceScaleSignals: [],
      importGraphs: [],
      selectorEvidence: []
    });
    const plan = renderStamped(footprint("b"));
    const stamps = { "namespace.shop.pod": footprint("a"), "process.shop.cron": footprint("b"), "process.shop.worker": footprint("b") };
    for (const type of ["diagram-runtime-topology", "runtime-topology-summary"]) {
      const file = plan.files.find((entry) => entry.target.type === type)!;
      expect(file.sourceStamps).toEqual(stamps);
      expect(plan.renderedTargets[file.target.targetId]!.sourceStamps).toEqual(stamps);
      expect(plan.renderedTargets[file.target.targetId]!.scale).toBeUndefined();
    }
    for (const target of plan.targets.filter((entry) => entry.type === "entity-summary")) {
      expect(plan.renderedTargets[target.targetId]!.sourceStamps).toBeUndefined();
    }
    const summary = plan.files.find((file) => file.target.type === "runtime-topology-summary")!.body;
    expect(summary).toContain("| `namespace.shop.pod` Shop pod | `k8s/*.yaml` |");
    expect(summary).toContain("| `process.shop.cron` Cron | `compose.yaml` |");
    expect(summary).toContain("| `process.shop.api-server` API server | model-authored, no source anchor |");

    // A moved configuration file changes the stamp only: the rendered bytes stay the same.
    const moved = renderStamped(footprint("c"));
    expect(moved.files.map(({ path, body }) => ({ path, body }))).toEqual(plan.files.map(({ path, body }) => ({ path, body })));
    expect(moved.manifest.body).not.toBe(plan.manifest.body);
  });
});

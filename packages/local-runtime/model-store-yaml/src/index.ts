/** Raised instead of writing when `init` would replace or complete an existing model (#167). */
export class ArchContextInitRefusedError extends Error {
  constructor(readonly existingPaths: string[]) {
    super(`archcontext-init-refused: .archcontext is already initialized or partially initialized (${existingPaths.join(", ")}); init never overwrites an existing model — change it through a ChangeSet, or remove these files deliberately before re-initializing`);
    this.name = "ArchContextInitRefusedError";
  }
}

/**
 * Creates the initial model. The files it writes are authoritative, so it is create-only: if any
 * of them already exists — even as a dangling symlink — nothing is written; each file is created
 * atomically without following symlinks in any path segment; and a failure part-way removes the
 * files this call created, so a failed init never leaves a silently half-initialized model.
 */
export function initializeArchContextModel(root: string, productName = "ArchContext Project"): void {
  const productId = `product.${productName.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "app"}`;
  const files: Array<{ path: string; body: string }> = [];
  const addYaml = (path: string, value: Json) => files.push({ path, body: stableYaml(value) });
  addYaml(".archcontext/manifest.yaml", createDefaultManifest(productId, productName));
  addYaml(".archcontext/product.yaml", {
    schemaVersion: "archcontext.product/v1",
    id: productId,
    name: productName,
    purpose: "Capture product intent for architecture-aware agent work.",
    users: [{ id: "developer", description: "Developer using an agentic coding runtime." }],
    capabilities: ["architecture-context"],
    successCriteria: ["Agent tasks bind to architecture context before completion."],
    nonGoals: [],
    riskDomains: []
  });
  addYaml(".archcontext/model/nodes/capability.architecture.context.yaml", {
    schemaVersion: "archcontext.node/v2",
    id: "capability.architecture.context",
    kind: "capability",
    name: "Architecture Context",
    status: "active",
    summary: "Keeps product and architecture intent available to coding agents."
  });
  addYaml(".archcontext/policies/review.yaml", {
    schemaVersion: "archcontext.policy/v1",
    id: "policy.review",
    failOn: [...REVIEW_FAIL_ON_CATEGORIES]
  });
  files.push({ path: ".archcontext/projections/targets.json", body: `${JSON.stringify(createDefaultProjectionTargetManifest(), null, 2)}\n` });

  // The repository root is the trusted containment boundary (it may itself be reached through a
  // symlink); only paths below it are checked. Creating it keeps init usable on a fresh directory.
  mkdirSync(root, { recursive: true });
  const existing = files.filter((file) => {
    assertPathHasNoSymlinkSegments(root, file.path);
    return lstatIfExists(resolve(root, file.path)) !== undefined;
  }).map((file) => file.path);
  if (existing.length > 0) throw new ArchContextInitRefusedError(existing);

  const created: string[] = [];
  try {
    for (const file of files) {
      writeFileWithoutFollowingSymlinks({ root, path: file.path, body: withTrailingNewline(file.body), expectedHash: "missing" });
      created.push(file.path);
    }
    // Part of the same all-or-nothing step: a failed rebuild must not leave an initialized model
    // behind that would refuse every retry.
    rebuildGeneratedProjection(root);
  } catch (error) {
    for (const path of created.reverse()) rmSync(resolve(root, path), { force: true });
    throw error;
  }
}

export function rebuildGeneratedProjection(root: string): void {
  for (const operation of planGeneratedProjection(root)) {
    // Generated files live in the repository too, so neither the delete nor the write may be
    // redirected through a committed symlink. `rm` does not follow a final symlink (a stale link is
    // simply removed), so a delete only needs link-free parent directories.
    if (operation.operation === "delete_entity") {
      assertPathHasNoSymlinkSegments(root, dirname(operation.path));
      rmSync(resolve(root, operation.path), { force: true });
    } else {
      writeFileWithoutFollowingSymlinks({ root, path: operation.path, body: withTrailingNewline(operation.body), expectedHash: operation.expectedHash });
    }
  }
}

export function planGeneratedProjection(root: string): GeneratedProjectionOperation[] {
  const desiredBody = GENERATED_ARCHITECTURE_BODY;
  const desiredAbsolute = resolve(root, GENERATED_ARCHITECTURE_PATH);
  const operations: GeneratedProjectionOperation[] = [];
  if (!existsSync(desiredAbsolute) || readFileSync(desiredAbsolute, "utf8") !== desiredBody) {
    operations.push({
      path: GENERATED_ARCHITECTURE_PATH,
      expectedHash: existsSync(desiredAbsolute) ? digestJson({ body: readFileSync(desiredAbsolute, "utf8") }) : "missing",
      body: desiredBody,
      operation: "render_projection"
    });
  }
  for (const path of collectGeneratedProjectionFiles(root)) {
    if (path === GENERATED_ARCHITECTURE_PATH) continue;
    const body = readFileSync(resolve(root, path), "utf8");
    operations.push({
      path,
      expectedHash: digestJson({ body }),
      body: "",
      operation: "delete_entity"
    });
  }
  return operations.sort((left, right) => left.path.localeCompare(right.path));
}

function collectGeneratedProjectionFiles(root: string): string[] {
  const generatedRoot = ".archcontext/generated";
  if (!existsSync(resolve(root, generatedRoot))) return [];
  const walk = (relativeDir: string): string[] => readdirSync(resolve(root, relativeDir), { withFileTypes: true })
    .flatMap((entry) => {
      const child = `${relativeDir}/${entry.name}`;
      if (entry.isDirectory()) return walk(child);
      return entry.isFile() ? [child] : [];
    });
  return walk(generatedRoot).sort();
}

export class YamlModelStore implements ModelStorePort {
  async loadManifest(workspace: WorkspaceRef): Promise<unknown> {
    return readFileSync(resolve(workspace.root, ".archcontext/manifest.yaml"), "utf8");
  }

  async loadModel(workspace: WorkspaceRef): Promise<ModelFile[]> {
    return listModelFiles(workspace.root);
  }

  async validateModel(workspace: WorkspaceRef): Promise<ModelValidationResult> {
    const errors: string[] = [];
    const nodeSchemaErrors: NonNullable<ModelValidationResult["nodeSchemaErrors"]> = [];
    for (const required of [".archcontext/manifest.yaml", ".archcontext/product.yaml"]) {
      try {
        readFileSync(resolve(workspace.root, required), "utf8");
      } catch {
        errors.push(`missing ${required}`);
      }
    }
    const files = listModelFiles(workspace.root);
    // Parsed node and relation records with their paths, for the cross-entity topology rules.
    const topologyRecords: { nodes: Record<string, Json>[]; relations: Record<string, Json>[] } = { nodes: [], relations: [] };
    const topologyRecordPaths = new Map<string, string>();
    for (const file of files) {
      if (file.path.startsWith(".archcontext/model/") && /\.ya?ml$/.test(file.path)) {
        try {
          const value = parseJsonOrStableYaml(file.body, file.path);
          for (const [directory, records] of [["nodes", topologyRecords.nodes], ["relations", topologyRecords.relations]] as const) {
            if (!file.path.startsWith(`.archcontext/model/${directory}/`) || !isJsonRecord(value)) continue;
            records.push(value);
            if (typeof value.id === "string") topologyRecordPaths.set(value.id, file.path);
          }
          if (file.path.startsWith(".archcontext/model/nodes/")) {
            const { issues } = validateJsonSchema(nodeSchema, value);
            for (const issue of issues) {
              const error = `${file.path}: ${issue.path}: ${issue.message}`;
              errors.push(error);
              nodeSchemaErrors.push({ path: file.path, error });
            }
            continue;
          }
        } catch (error) {
          errors.push(`${file.path}: invalid model YAML: ${error instanceof Error ? error.message : String(error)}`);
          continue;
        }
      }
      if (!file.schemaVersion.startsWith("archcontext.")) errors.push(`${file.path}: missing schemaVersion`);
      if (file.path.startsWith(".archcontext/model/flows/") && file.schemaVersion !== "archcontext.flow/v1") {
        errors.push(`${file.path}: expected archcontext.flow/v1, got ${file.schemaVersion || "missing"}`);
      }
    }
    for (const issue of runtimeTopologyModelIssues(topologyRecords)) {
      errors.push(`${topologyRecordPaths.get(issue.entityId) ?? issue.entityId}: ${issue.field}: ${issue.invariant}`);
    }
    const adr = validateAdrAppliesTo(files);
    const constraints = readDependencyConstraints(files);
    const reviewPolicy = readReviewPolicy(files);
    errors.push(...adr.errors, ...constraints.errors, ...reviewPolicy.errors);
    const referenceErrors = [...adr.referenceErrors, ...constraints.referenceErrors];
    const warnings = [...constraints.warnings, ...reviewPolicy.warnings, ...manifestDecisionDiagnostics(files)];
    const modelDigest = digestJson(files.map((file) => ({ path: file.path, digest: file.digest })));
    return {
      valid: errors.length === 0,
      errors,
      ...(referenceErrors.length > 0 ? { referenceErrors } : {}),
      ...(nodeSchemaErrors.length > 0 ? { nodeSchemaErrors } : {}),
      ...(warnings.length > 0 ? { warnings } : {}),
      modelDigest
    };
  }

  async writeChangeSetPreview(changeSet: unknown): Promise<{ digest: string; summary: string }> {
    return { digest: digestJson(changeSet as Json), summary: "ChangeSet preview generated" };
  }
}

/**
 * The architecture model authority that must be committed. A manifest digest and generated
 * documents cannot rebuild it, so an ignore rule over any of these paths leaves the model in one
 * checkout only. `generated` is a rebuildable projection and is not listed.
 */
export const ARCHITECTURE_MODEL_COMMITTED_PATHS = Object.freeze([
  ".archcontext/manifest.yaml",
  ".archcontext/product.yaml",
  ".archcontext/model/nodes/",
  ".archcontext/model/relations/",
  ".archcontext/model/flows/",
  ".archcontext/decisions/",
  ".archcontext/policies/",
  ".archcontext/practices/",
  ".archcontext/projections/"
] as const);

/**
 * The paths whose ignore status decides whether the model can be committed: the committed paths
 * plus every model file present under their directories. A directory probe alone misses a file
 * rule such as `.archcontext/model/nodes/*.yaml` that leaves the directory itself visible.
 */
export function architectureModelIgnoreProbePaths(root: string): string[] {
  const directories = ARCHITECTURE_MODEL_COMMITTED_PATHS.filter((path) => path.endsWith("/")).map((path) => path.slice(0, -1));
  return [...new Set([...ARCHITECTURE_MODEL_COMMITTED_PATHS, ...collectArchContextFiles(root, directories)])];
}

export function listModelFiles(root: string): ModelFile[] {
  const paths = collectArchContextFiles(root, [
    ".archcontext/manifest.yaml",
    ".archcontext/product.yaml",
    ".archcontext/model",
    ".archcontext/decisions",
    ".archcontext/policies",
    ".archcontext/practices",
    ".archcontext/projections",
    ".archcontext/generated",
    "docs/adr"
  ]);
  return paths.map((path) => {
    const body = readFileSync(resolve(root, path), "utf8");
    return {
      path,
      body,
      schemaVersion: extractSchemaVersion(body, path),
      digest: digestJson({ path, body })
    };
  });
}

function collectArchContextFiles(root: string, entries: string[]): string[] {
  const files: string[] = [];
  for (const entry of entries) {
    const absolute = resolve(root, entry);
    if (!existsSync(absolute)) continue;
    const stat = readdirOrFile(absolute);
    if (stat === "file") {
      files.push(entry);
      continue;
    }
    for (const child of walk(entry)) files.push(child);
  }
  return [...new Set(files)].sort();

  function walk(relativeDir: string): string[] {
    const out: string[] = [];
    const dir = resolve(root, relativeDir);
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const child = `${relativeDir}/${entry.name}`;
      if (entry.isDirectory()) out.push(...walk(child));
      if (entry.isFile() && /\.(ya?ml|md)$/.test(entry.name) && isCollectableModelFile(child)) out.push(child);
    }
    return out;
  }
}

function isCollectableModelFile(path: string): boolean {
  if (path.startsWith("docs/adr/")) return /^docs\/adr\/ADR-\d{4}-.+\.md$/.test(path);
  return true;
}

function readdirOrFile(path: string): "directory" | "file" {
  try {
    readdirSync(path);
    return "directory";
  } catch {
    return "file";
  }
}

function extractSchemaVersion(body: string, path: string): string {
  if (path.startsWith(".archcontext/model/") && /\.ya?ml$/.test(path)) {
    try {
      const parsed = parseJsonOrStableYaml(body, path) as { schemaVersion?: unknown } | null;
      return typeof parsed?.schemaVersion === "string" ? parsed.schemaVersion : "";
    } catch {
      // Keep loading malformed files so validateModel can return their path-specific diagnostics.
      return "";
    }
  }
  const match = body.match(/schemaVersion:\s*"?([^"\n]+)"?/);
  if (match) return match[1].trim();
  try {
    const parsed = JSON.parse(body) as { schemaVersion?: unknown };
    if (typeof parsed.schemaVersion === "string") return parsed.schemaVersion;
  } catch {
    // JSON-compatible YAML is optional; plain YAML remains supported above.
  }
  if (body.includes("Generated by ArchContext")) return "archcontext.generated/v1";
  return "";
}

function isJsonRecord(value: unknown): value is Record<string, Json> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function withTrailingNewline(body: string): string {
  return body.endsWith("\n") ? body : `${body}\n`;
}

function lstatIfExists(path: string) {
  try {
    return lstatSync(path);
  } catch {
    return undefined;
  }
}
